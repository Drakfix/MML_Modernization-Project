"""patch_data.h for gamefiles.c (the runtime patches the player's exe where there is no installer:
Android, Linux) from src/patch_manifest.py. Used by android/build_android.py and linux/build_linux.py."""
import os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def patch_data(inc):
    """patch_data.h: the installer's exe patches (src/patch_manifest.py) for gamefiles.c, one entry
    per edition the manifest has: the US MEGAMAN.EXE, and the Japanese ROCKMAN.EXE when it was built
    with a Japanese copy"""
    m = {}
    exec(open(os.path.join(REPO, "src", "patch_manifest.py"), encoding="utf-8").read(), m)

    def arr(b):
        return ",".join("0x%02x" % x for x in b) or "0"
    eds = [("US", "MEGAMAN.EXE", "MEGAMAN_NATIVE.EXE", m["VANILLA_SHA256"], m["PATCHED_SHA256"],
            m["PREVIOUS_PATCHED_SHA256"], m["EXE_SIZE"], m["PATCHES"], m["EXE_TAIL"])]
    if m.get("JP_EXE"):
        eds.append(("JP", m["JP_EXE"], "ROCKMAN_NATIVE.EXE", m["JP_VANILLA_SHA256"], m["JP_PATCHED_SHA256"],
                    [], m["JP_EXE_SIZE"], m["JP_PATCHES"], m["JP_EXE_TAIL"]))
    out = ["/* GENERATED by native/patch_data.py from src/patch_manifest.py: do not edit */",
           "#include <stdint.h>",
           "typedef struct { uint32_t off, at, len; } pd_run;",
           "typedef struct {",
           "    const char *exe, *native, *vanilla, *patched;",
           "    const char *const *previous; int nprevious;",
           "    uint32_t exe_size, patched_size;",
           "    const pd_run *runs; int nruns;",
           "    const uint8_t *bytes, *tail;",
           "} pd_edition;"]
    rows = []
    for tag, exe, native_name, van, pat, prev, size, patches, tail_hex in eds:
        runs, data = [], bytearray()
        for off, hexbytes in patches:
            b = bytes.fromhex(hexbytes)
            runs.append((off, len(data), len(b)))
            data += b
        tail = bytes.fromhex(tail_hex)
        out += ["static const char *const PD_PREVIOUS_%s[] = { %s };" % (tag, ", ".join('"%s"' % h for h in prev) or "0"),
                "static const pd_run PD_RUNS_%s[] = { %s };" % (tag, ", ".join("{ %du, %du, %du }" % r for r in runs)),
                "static const uint8_t PD_BYTES_%s[] = { %s };" % (tag, arr(data)),
                "static const uint8_t PD_TAIL_%s[] = { %s };" % (tag, arr(tail))]
        rows.append('    { "%s", "%s", "%s", "%s", PD_PREVIOUS_%s, %d, %du, %du, PD_RUNS_%s, %d, PD_BYTES_%s, PD_TAIL_%s },' % (
            exe, native_name, van, pat, tag, len(prev), size, size + len(tail), tag, len(runs), tag, tag))
    out += ["static const pd_edition PD_EDITIONS[] = {"] + rows + ["};",
            "#define PD_NEDITIONS %d" % len(rows)]
    with open(os.path.join(inc, "patch_data.h"), "w") as f:
        f.write("\n".join(out) + "\n")
