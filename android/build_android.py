"""Builds the Android app (android/build/mml.apk) with the Android SDK's own tools, no Gradle:
the native code with the NDK's clang (arm64-v8a), SDL3's Java glue and ours with javac and d8,
the manifest and resources with aapt2, then zipalign and apksigner (a debug key made on first use).

    python android/build_android.py [--install] [--hello]

Needs (defaults in parentheses; environment variables override them):
  ANDROID_SDK   the Android SDK (%LOCALAPPDATA%\\Android\\Sdk), with build-tools, platforms and ndk
  JAVA_HOME     a JDK 17 or 21 (Android Studio's own, jbr)
  SDL3_SRC      SDL3's source (mml-deps\\SDL3-3.4.18 next to the repo): its Java glue and headers
  SDL3_ANDROID  SDL3 built for Android (mml-deps\\SDL3-android): <abi>\\libSDL3.so
  MML_KEYSTORE  the signing key (mml-deps\\android\\debug.keystore, made if missing)
  MML_INTRO     our intro video to bundle (else MML_GAME_DIR\\Modernization\\intro.mpg): the app puts
                it in place next to the player's game files
--install puts the app on the connected device with adb; --hello builds the step-A test instead of
the game (android/hello: Vulkan clears the screen).
"""
import os
import shutil
import subprocess
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
DEPS = os.path.join(os.path.dirname(REPO), "mml-deps")
ABI = "arm64-v8a"
MIN_SDK = 28   # Android 9: Vulkan 1.1
TARGET_SDK = 35


def env(name, default):
    return os.environ.get(name) or default


SDK = env("ANDROID_SDK", os.path.join(os.environ.get("LOCALAPPDATA", ""), "Android", "Sdk"))
JDK = env("JAVA_HOME", r"C:\Program Files\Android\Android Studio\jbr")
SDL_SRC = env("SDL3_SRC", os.path.join(DEPS, "SDL3-3.4.18"))
SDL_LIB = env("SDL3_ANDROID", os.path.join(DEPS, "SDL3-android"))
KEYSTORE = env("MML_KEYSTORE", os.path.join(DEPS, "android", "debug.keystore"))
OUT = os.path.join(HERE, "build")


def newest(path):
    return os.path.join(path, sorted(os.listdir(path))[-1])


BUILD_TOOLS = newest(os.path.join(SDK, "build-tools"))
NDK = newest(os.path.join(SDK, "ndk"))
ANDROID_JAR = os.path.join(SDK, "platforms", "android-%d" % TARGET_SDK, "android.jar")
# clang itself, with the target the NDK's .cmd wrappers add (their command line is too short for
# the link)
CLANG = os.path.join(NDK, "toolchains", "llvm", "prebuilt", "windows-x86_64", "bin", "clang.exe")
TARGET = "--target=aarch64-linux-android%d" % MIN_SDK


def run(*cmd):
    print(os.path.basename(cmd[0]), *[os.path.basename(c) if os.path.isabs(c) else c for c in cmd[1:8]],
          "..." if len(cmd) > 8 else "")
    subprocess.run(list(cmd), check=True)


NATIVE = os.path.join(REPO, "native")
GEN = os.path.join(NATIVE, "build", "gen")   # the recompiled game (tools/recomp; never committed)
# Windows-only sources: Direct3D 11 and its shader runtime, GDI fonts, the Windows platform and
# window placement, debugging tools; recomp_native.c compiles to nothing without machine code
WINDOWS_ONLY = {"gfx_d3d11.c", "rshader.c", "ui_font_gdi.c", "plat_win32.c", "gfx_win.c", "iat.c",
                "apicensus.c", "sampler.c", "watch.c", "kbm.c", "recomp_native.c"}
# -fno-semantic-interposition and -Bsymbolic (link): calls and data inside libmain.so go direct,
# not through the PLT and GOT as for symbols another library could replace (53,577 PLT calls)
CLANGXX_FLAGS = ["-fPIC", "-O2", "-fno-semantic-interposition", "-fms-extensions", "-DMML_RUNNER", "-DMML_VULKAN",
                 "-DMML_PATCH_DATA"]


def newer(src, obj):
    return not os.path.exists(obj) or os.path.getmtime(src) > os.path.getmtime(obj)


def compile_many(jobs):
    """(source, object, extra flags) in parallel; stops at the first failure"""
    from concurrent.futures import ThreadPoolExecutor

    def one(job):
        src, obj, extra = job
        r = subprocess.run([CLANG, TARGET, "-c", *CLANGXX_FLAGS, *extra, src, "-o", obj], capture_output=True,
                           text=True)
        return src, r

    failed = []
    with ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as pool:
        for src, r in pool.map(one, jobs):
            if r.returncode:
                failed.append(src)
                print(r.stderr)
    if failed:
        sys.exit("failed: " + ", ".join(os.path.basename(f) for f in failed))


def patch_data(inc):
    """patch_data.h: the installer's exe patch (src/patch_manifest.py) for gamefiles.c"""
    m = {}
    exec(open(os.path.join(REPO, "src", "patch_manifest.py"), encoding="utf-8").read(), m)
    runs, data = [], bytearray()
    for off, hexbytes in m["PATCHES"]:
        b = bytes.fromhex(hexbytes)
        runs.append((off, len(data), len(b)))
        data += b
    tail = bytes.fromhex(m["EXE_TAIL"])

    def arr(b):
        return ",".join("0x%02x" % x for x in b)
    out = ["/* GENERATED by android/build_android.py from src/patch_manifest.py: do not edit */",
           "#include <stdint.h>",
           '#define PD_VANILLA_SHA256 "%s"' % m["VANILLA_SHA256"],
           '#define PD_PATCHED_SHA256 "%s"' % m["PATCHED_SHA256"],
           "static const char *const PD_PREVIOUS[] = { %s };" % ", ".join('"%s"' % h for h in m["PREVIOUS_PATCHED_SHA256"]),
           "#define PD_EXE_SIZE %du" % m["EXE_SIZE"],
           "#define PD_PATCHED_SIZE %du" % m["PATCHED_SIZE"],
           "static const struct { uint32_t off, at, len; } PD_RUNS[] = { %s };" %
           ", ".join("{ %du, %du, %du }" % r for r in runs),
           "#define PD_NRUNS %d" % len(runs),
           "static const uint8_t PD_BYTES[] = { %s };" % arr(data),
           "static const uint8_t PD_TAIL[] = { %s };" % arr(tail)]
    assert m["PATCHED_SIZE"] - m["EXE_SIZE"] == len(tail)
    with open(os.path.join(inc, "patch_data.h"), "w") as f:
        f.write("\n".join(out) + "\n")


def assets():
    """the files bundled in the app: our intro (none of the game's)"""
    d = os.path.join(OUT, "assets")
    shutil.rmtree(d, ignore_errors=True)
    os.makedirs(d)
    intro = os.environ.get("MML_INTRO") or os.path.join(os.environ.get("MML_GAME_DIR", ""), "Modernization", "intro.mpg")
    shutil.copyfile(os.path.join(REPO, "config", "mml.ini"), os.path.join(d, "mml.ini"))   # our defaults
    # the licenses of what the app is made of (ours, SDL3, pl_mpeg)
    os.makedirs(os.path.join(d, "licenses"))
    shutil.copyfile(os.path.join(REPO, "LICENSE"), os.path.join(d, "licenses", "LICENSE.txt"))
    shutil.copyfile(os.path.join(REPO, "THIRD-PARTY-NOTICES.txt"), os.path.join(d, "licenses", "THIRD-PARTY-NOTICES.txt"))
    for f in ("SDL3-LICENSE.txt", "pl_mpeg-LICENSE.txt"):
        shutil.copyfile(os.path.join(REPO, "licenses", f), os.path.join(d, "licenses", f))
    if os.path.isfile(intro):
        shutil.copyfile(intro, os.path.join(d, "intro.mpg"))
    else:
        print("WARNING: no intro.mpg (MML_INTRO or MML_GAME_DIR): the app shows the game's own intro")
    return d


def shaders(inc):
    glslc = os.path.join(NDK, "shader-tools", "windows-x86_64", "glslc.exe")
    os.makedirs(os.path.join(inc, "shaders"), exist_ok=True)
    for name in ("game", "blit", "ui"):
        for stage in ("vert", "frag"):
            run(glslc, "-O", "--target-env=vulkan1.1", "-mfmt=c", os.path.join(NATIVE, "shaders", "vk",
                "%s.%s" % (name, stage)), "-o", os.path.join(inc, "shaders", "vk_%s_%s.inc" % (name, stage)))


def native():
    """libmain.so: the runtime, our mods and the recompiled game (native/build/gen, needed)"""
    lib = os.path.join(OUT, "lib", ABI)
    inc = os.path.join(OUT, "include")
    obj = os.path.join(OUT, "obj")
    gen_obj = os.path.join(OUT, "gen_obj")
    for d in (lib, obj, gen_obj):
        os.makedirs(d, exist_ok=True)
    if not os.path.exists(os.path.join(GEN, "recomp_table.c")):
        sys.exit("no recompiled code in native/build/gen (tools/recomp/README.md)")
    shaders(inc)
    patch_data(inc)
    src_dir = os.path.join(NATIVE, "src")
    flags = ["-Wall", "-Wno-unused-parameter", "-Wno-unused-function", "-Wno-missing-braces",
             "-I", os.path.join(NATIVE, "compat"), "-I", inc, "-I", src_dir, "-I", os.path.join(SDL_SRC, "include")]
    sources = sorted(f for f in os.listdir(src_dir) if f.endswith(".c") and f not in WINDOWS_ONLY)
    jobs = [(os.path.join(src_dir, f), os.path.join(obj, f[:-2] + ".o"), flags) for f in sources]
    print("compiling %d sources" % len(jobs))
    compile_many(jobs)
    gen_jobs = []
    for f in sorted(os.listdir(GEN)):
        if f.endswith(".c"):
            o = os.path.join(gen_obj, f[:-2] + ".o")
            if newer(os.path.join(GEN, f), o):
                gen_jobs.append((os.path.join(GEN, f), o, ["-w", "-I", src_dir]))
    if gen_jobs:
        print("compiling %d generated files (the recompiled game)" % len(gen_jobs))
        compile_many(gen_jobs)
    objs = [j[1] for j in jobs] + [os.path.join(gen_obj, f) for f in sorted(os.listdir(gen_obj))]
    rsp = os.path.join(OUT, "objects.rsp")   # (too many for one command line)
    with open(rsp, "w") as f:
        f.write("\n".join('"%s"' % o.replace("\\", "/") for o in objs))
    run(CLANG, TARGET, "-shared", "-fPIC", "-Wl,--no-undefined", "-Wl,-Bsymbolic", "-o", os.path.join(lib, "libmain.so"), "@" + rsp,
        "-L", os.path.join(SDL_LIB, ABI), "-lSDL3", "-llog", "-landroid", "-lm", "-ldl")
    shutil.copy(os.path.join(SDL_LIB, ABI, "libSDL3.so"), lib)


def native_hello():
    """libmain.so: the step-A test (android/hello) instead"""
    lib = os.path.join(OUT, "lib", ABI)
    os.makedirs(lib, exist_ok=True)
    run(CLANG, TARGET, "-shared", "-fPIC", "-O2", "-Wall",
        "-I", os.path.join(SDL_SRC, "include"),
        os.path.join(HERE, "hello", "hello.c"),
        "-L", os.path.join(SDL_LIB, ABI), "-lSDL3", "-llog", "-landroid", "-lm",
        "-o", os.path.join(lib, "libmain.so"))
    shutil.copy(os.path.join(SDL_LIB, ABI, "libSDL3.so"), lib)


def java():
    """classes.dex: SDL3's activity (from its source) and ours"""
    classes = os.path.join(OUT, "classes")
    shutil.rmtree(classes, ignore_errors=True)
    os.makedirs(classes)
    sources = []
    for root in (os.path.join(SDL_SRC, "android-project", "app", "src", "main", "java"), os.path.join(HERE, "java")):
        for d, _, files in os.walk(root):
            sources += [os.path.join(d, f) for f in files if f.endswith(".java")]
    run(os.path.join(JDK, "bin", "javac.exe"), "-nowarn", "-encoding", "UTF-8", "--release", "11", "-classpath",
        ANDROID_JAR, "-d", classes, *sources)
    class_files = [os.path.join(d, f) for d, _, fs in os.walk(classes) for f in fs if f.endswith(".class")]
    run(os.path.join(BUILD_TOOLS, "d8.bat"), "--release", "--min-api", str(MIN_SDK), "--lib", ANDROID_JAR,
        "--output", OUT, *class_files)


def package():
    """the manifest and resources (aapt2), then the dex and native libraries added"""
    res_flat = os.path.join(OUT, "res.zip")
    base = os.path.join(OUT, "base.apk")
    run(os.path.join(BUILD_TOOLS, "aapt2.exe"), "compile", "--dir", os.path.join(HERE, "res"), "-o", res_flat)
    run(os.path.join(BUILD_TOOLS, "aapt2.exe"), "link", "-o", base, "-I", ANDROID_JAR,
        "--manifest", os.path.join(HERE, "AndroidManifest.xml"), "--min-sdk-version", str(MIN_SDK),
        "--target-sdk-version", str(TARGET_SDK), "-A", assets(), res_flat)
    with zipfile.ZipFile(base, "a", zipfile.ZIP_DEFLATED) as z:
        z.write(os.path.join(OUT, "classes.dex"), "classes.dex")
        lib = os.path.join(OUT, "lib", ABI)
        for f in sorted(os.listdir(lib)):
            z.write(os.path.join(lib, f), "lib/%s/%s" % (ABI, f))
    return base


def sign(base):
    aligned = os.path.join(OUT, "aligned.apk")
    apk = os.path.join(OUT, "mml.apk")
    if not os.path.exists(KEYSTORE):   # a debug key, as Android Studio makes one
        os.makedirs(os.path.dirname(KEYSTORE), exist_ok=True)
        run(os.path.join(JDK, "bin", "keytool.exe"), "-genkeypair", "-keystore", KEYSTORE, "-storepass", "android",
            "-keypass", "android", "-alias", "androiddebugkey", "-keyalg", "RSA", "-keysize", "2048",
            "-validity", "10000", "-dname", "CN=Android Debug,O=Android,C=US")
    run(os.path.join(BUILD_TOOLS, "zipalign.exe"), "-f", "-p", "4", base, aligned)
    run(os.path.join(BUILD_TOOLS, "apksigner.bat"), "sign", "--ks", KEYSTORE, "--ks-pass", "pass:android",
        "--key-pass", "pass:android", "--out", apk, aligned)
    return apk


def main():
    os.makedirs(OUT, exist_ok=True)
    os.environ["JAVA_HOME"] = JDK   # (d8 and apksigner run on it too)
    native_hello() if "--hello" in sys.argv else native()
    java()
    apk = sign(package())
    print("built", apk)
    if "--install" in sys.argv:
        run(os.path.join(SDK, "platform-tools", "adb.exe"), "install", "-r", apk)


if __name__ == "__main__":
    main()
