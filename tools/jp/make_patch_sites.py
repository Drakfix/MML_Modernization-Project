"""tools/recomp/patch_sites_jp.txt: the places mml.dll patches at runtime, in the Japanese
rockman.exe, for the recompiler (tools/recomp/recomp.py, on the Japanese Ghidra project).

    python tools/jp/make_patch_sites.py

Every line of patch_sites.txt with its address translated (tools/jp/addr_map.py), and the
operands of the Japanese button tests that input.c gives the US buttons back ([controls]
jp_buttons=us), read from its table g_jp_buttons: the generated code reads them from memory, so
the setting works in the recompiled game too."""
import os
import re

from addr_map import jp

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, '..', '..'))
SRC = os.path.join(REPO, 'tools', 'recomp', 'patch_sites.txt')
OUT = os.path.join(REPO, 'tools', 'recomp', 'patch_sites_jp.txt')
INPUT_C = os.path.join(REPO, 'native', 'src', 'input.c')


def main():
    out = ['# GENERATED by tools/jp/make_patch_sites.py from patch_sites.txt and native/src/input.c',
           '# (g_jp_buttons): do not edit. The Japanese rockman.exe; columns as in patch_sites.txt.']
    n = 0
    for line in open(SRC, encoding='utf-8'):
        p = line.split()
        if not p or line.startswith('#'):
            continue
        out.append('%08X %s %s %s' % (jp(int(p[0], 16)), p[1], p[2], p[3]))
        n += 1
    src = open(INPUT_C, encoding='utf-8').read()
    rows = re.findall(r'\{ 0x([0-9A-F]+)u, (\d+), "((?:\\x[0-9A-F]{2})+)", "((?:\\x[0-9A-F]{2})+)" \}', src)
    if len(rows) != 29:
        raise SystemExit('expected the 29 rows of g_jp_buttons in input.c, found %d' % len(rows))
    for at, size, jpb, usb in rows:
        jb = bytes(int(x, 16) for x in re.findall(r'\\x([0-9A-F]{2})', jpb))
        ub = bytes(int(x, 16) for x in re.findall(r'\\x([0-9A-F]{2})', usb))
        imm = 2 if jb[0] == 0x66 else 1   # 16-bit operand size prefix: a 2-byte immediate
        if jb[:-imm] != ub[:-imm]:
            raise SystemExit('row %s: the instructions differ outside the immediate' % at)
        out.append('%08X %d P %02X' % (jp(int(at, 16)) + int(size) - imm, imm, ub[-imm]))
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print('%d sites translated, %d button operands; wrote %s' % (n, len(rows), OUT))


if __name__ == '__main__':
    main()
